'use strict';
// Land dots for the homepage hero globe (home_scroll.js layer, 2026-10-13).
// Source: Natural Earth 1:110m land (public domain), scripts/country-pages/data/ne_110m_land.geojson.
// An even Fibonacci-sphere sample is kept where it falls on land, then packed 4 characters per dot
// (latitude and longitude in tenths of a degree, 12 bits each, base-64) into assets/js/home-globe-dots.js.
//   node scripts/country-pages/home_globe_dots.js [samples=11000]
const fs = require('fs'); const path = require('path');
const L = require('./lib.js');
const N = +(process.argv[2] || 11000);
const g = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/ne_110m_land.geojson'), 'utf8'));
const polys = g.features.map(f => f.geometry.coordinates).map(rings => {
  const xs = rings[0].map(p => p[0]), ys = rings[0].map(p => p[1]);
  return { rings, box: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)] };
});
function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function onLand(lon, lat) {
  for (const p of polys) {
    const b = p.box; if (lon < b[0] || lon > b[2] || lat < b[1] || lat > b[3]) continue;
    if (inRing(lon, lat, p.rings[0]) && !p.rings.slice(1).some(h => inRing(lon, lat, h))) return true;
  }
  return false;
}
const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
const enc = v => B64[(v >> 6) & 63] + B64[v & 63];
let out = '', n = 0; const golden = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2, r = Math.sqrt(1 - y * y), th = golden * i;
  const lat = Math.asin(y) * 180 / Math.PI, lon = ((Math.atan2(Math.sin(th) * r, Math.cos(th) * r) * 180 / Math.PI) + 540) % 360 - 180;
  if (lat < -60) continue;                       // no Antarctica: it only ever shows as a white cap
  if (!onLand(lon, lat)) continue;
  out += enc(Math.round(lat * 10) + 900) + enc(Math.round(lon * 10) + 1800); n++;
}
const js = `/* home-globe-dots.js -- ${n} land dots for the homepage hero globe. Generated by scripts/country-pages/home_globe_dots.js
   from Natural Earth 1:110m land (public domain). 4 chars per dot: lat*10+900, lon*10+1800, 12 bits each, base-64. */
window.TAP_GLOBE_DOTS = "${out}";
`;
L.write('assets/js/home-globe-dots.js', js);
console.log(n, 'land dots,', (js.length / 1024).toFixed(1) + 'KB');
