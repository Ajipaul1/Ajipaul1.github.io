// Builds api/_knowledge.js: the pages of the website, cut into short passages, for the TAP Assistant brain (api/tap-chat.js).
// Only pages in sitemap.xml. Run it after any change to page content:   node scripts/seo/build_chat_knowledge.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..'), SIZE = 800, PER_PAGE = 8;
const decode = (s) => s.replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#0?39;|&rsquo;|&lsquo;/g, "'").replace(/&ldquo;|&rdquo;/g, '"').replace(/&mdash;|&ndash;/g, '-').replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n));
const strip = (h) => decode(h.replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();
function faqs(html) {
  const out = [];
  for (const m of html.matchAll(/<script[^>]*application\/ld\+json[^>]*>([\s\S]*?)<\/script>/gi)) {
    try { (function walk(n) { if (Array.isArray(n)) return n.forEach(walk); if (!n || typeof n !== 'object') return; if (n['@type'] === 'Question' && n.acceptedAnswer?.text) out.push(`${n.name} ${strip(n.acceptedAnswer.text)}`); Object.values(n).forEach(walk); })(JSON.parse(m[1])); } catch (_) { /* a bad block is skipped */ }
  }
  return out;
}
function chunks(text) {
  const parts = [], s = text.split(/(?<=[.?!])\s+/); let c = '';
  for (const x of s) { if ((c + ' ' + x).length > SIZE && c) { parts.push(c.trim()); c = ''; } c += ' ' + x; }
  if (c.trim().length > 60) parts.push(c.trim());
  return parts;
}
const urls = [...fs.readFileSync(path.join(ROOT, 'sitemap.xml'), 'utf8').matchAll(/<loc>(.*?)<\/loc>/g)].map((m) => new URL(m[1]).pathname);
const out = [];
for (const u of urls) {
  const f = path.join(ROOT, u.replace(/^\//, ''), u.endsWith('/') ? 'index.html' : '');
  if (!fs.existsSync(f)) continue;
  const html = fs.readFileSync(f, 'utf8');
  const title = strip((html.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || [])[1] || u).slice(0, 120);
  const desc = decode((html.match(/<meta\s+name="description"\s+content="([^"]*)"/i) || [])[1] || '');
  const body = strip(html.replace(/<(script|style|noscript|svg|nav|header|footer|template)\b[\s\S]*?<\/\1>/gi, ' '));
  const list = [...faqs(html).map((q) => q.slice(0, SIZE)), ...chunks(body)].filter((t, i, a) => t.length > 40 && a.indexOf(t) === i).slice(0, PER_PAGE);
  if (desc) list.unshift(desc);
  list.forEach((t) => out.push({ u, ti: title, t }));
}
fs.writeFileSync(path.join(ROOT, 'api', '_knowledge.js'), `// Generated by scripts/seo/build_chat_knowledge.js. Do not edit by hand.\nexport default ${JSON.stringify(out)};\n`);
console.log(`${out.length} passages from ${new Set(out.map((x) => x.u)).size} pages`);
